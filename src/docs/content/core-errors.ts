/**
 * Every error `src/core` throws, with the judgement a generator cannot supply.
 *
 * The **message** of each entry is checked against the `throw` sites in `src/core`
 * by `src/tests/docs/coreLogs.test.ts`, in both directions: a new `throw` that is
 * not declared here fails the test, and a declaration nothing throws fails it too.
 * What cannot be read from the source — recoverable or fatal, the cause, the fix —
 * is written by hand, because `.claude/rules/guide.md` forbids documenting an error
 * without it.
 *
 * The core layer differs from a feature in one way worth knowing before reading the
 * page it produces: most of these throws are **caught by core itself**. A reader
 * chasing a broken page needs to know whether an error reached them or was swallowed
 * and logged, so every entry that is caught says so in {@link CoreErrorDoc.caught}
 * and names the log line it turns into — which is in
 * [logs.md](../guide/reference/logs.md).
 *
 * Build-time only, like the feature manifests and `sdk-attributes.ts`: nothing under
 * `src/` may import this, or the prose ships in the bundle that loads on customer
 * landing pages.
 */

import type { ErrorDoc } from '../schema/feature-manifest';

/** One error thrown somewhere in `src/core`. */
export interface CoreErrorDoc extends ErrorDoc {
  /**
   * The subsystem that throws it, as the logger prefix a reader sees in the console
   * — `SDKInitializer`, `CountryService`. Matches a `prefix` in `core-logs.ts` so the
   * two pages line up.
   */
  owner: string;
  /**
   * Path of the throwing file, relative to `src/core`. Checked against the source, so
   * an error that moves to another file cannot keep a stale location on the page.
   */
  file: string;
  /**
   * What catches it and what the visitor is left with. Omit for an error that
   * genuinely propagates to the caller — then the page says the caller sees it.
   */
  caught?: string;
  /**
   * The message as `extract-logs.ts` renders it, for the few throws where that reads
   * worse than the truth.
   *
   * The extractor turns a `${…}` into `{lastDotSegment}`, which is right for
   * `${this.selectorId}` → `{selectorId}` and wrong for a ternary: `${error instanceof
   * Error ? error.message : String(error)}` comes out as `{message : String(error)}`,
   * which is not something a reader would ever type into a search box. Set this to that
   * exact string and put the readable form in {@link ErrorDoc.message} — the drift check
   * uses this one, so the tie to the source is unchanged, and the page shows the other.
   */
  extracted?: string;
}

